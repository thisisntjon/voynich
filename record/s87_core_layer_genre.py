    nat("P_cremma_prose_la", "P", meta_lines(ROOT / "data" / "controls_realline" / "cremma_all.meta.json", set(CREMMA_PROSE)),
        True, "CREMMA prose manuscripts, Latin, real manuscript lines")
    nat("P_caesar_la", "P", load_control("latin_caesar.txt"), False, "Caesar, De bello Gallico, Latin prose")
    nat("P_augustine_la", "P", load_control("latin_augustine.txt"), False, "Augustine, Latin prose")
    nat("P_pliny_herbal_la", "P", load_control("latin_pliny_herbal.txt"), False, "Pliny NH XX-XXVII, Latin prose on plants")
    nat("P_mandeville_en", "P", load_mandeville(), False, "Mandeville's Travels, English prose")
    nat("P_alice_en", "P", load_control("english_alice.txt"), False, "Alice in Wonderland, English prose")
    for nm, f, lab in (("V_dante_it", "italian_dante", "Dante, Italian verse"),
                       ("V_nibelungenlied_gmh", "mhg_nibelungenlied", "Nibelungenlied, MHG verse"),
                       ("V_croisade_oc", "occitan_croisade", "Canso de la crozada, Occitan verse"),
                       ("V_roland_fro", "oldfrench_roland", "Chanson de Roland, Old French verse")):
        nat(nm, "V", meta_lines(ROOT / "data" / "controls_realline" / f"{f}.meta.json"), True, lab + ", real verse lines")
    texts.append(("G_s57_localmem", "G", True, layout(None, True, meta_pages(ROOT / "runs" / "s57" / "gen_ZL3b_s1.meta.json"),
                                                         line_lens, page_nl), "slot", False, "s57 local-memory generator (ZL3b fit, seed 1)"))
    ca = []
    for f in sorted((ROOT / "runs" / "s67").glob("CA_ZL3b_*_s1.meta.json")):
        ca.extend((f"{f.stem}:{pid}" if AMEND1 else pid, ls) for pid, ls in meta_pages(f))   # AMENDMENT 1: unique ids
    texts.append(("G_s67_CA", "G", True, layout(None, True, ca, line_lens, page_nl), "slot", False,
                  "s67 constrained assembly, ZL3b LOQO folds (seed 1) concatenated"))
    gen = build_pool_gens(zl)
    texts.append(("G_pagepool", "G", True, layout(None, True, gen(None, SEED + 11), line_lens, page_nl), "id", False,
                  "page-pool generator (ZL3b page core pools, 0 free params)"))
    flush()

    # ---- N_match
    gating_or_voy = [t for t in texts if t[2] or t[1] == "VOY"]
    held = {t[0]: prepared_held_out(t[0], t[3], t[4]) for t in gating_or_voy}
    n_match = min(held.values())

    # ---- line-pool fit (R_within(1) of the ZL3b cut)
    zl_cut = texts[0][3]
    tz = [w for _, ls in zl_cut for ln in ls for w in ln]
    segz = SlotSegmenter(tz)
    cz, pz, lz, bz, _ = flatten(zl_cut, lambda w: segz.segment(w)[1])
    target_rw = repetition(cz, pz, lz, 200, SEED)[1]["Rw"]
    fit_rows = []
    for a in ALPHAS:
        gp = layout(None, True, gen(a, SEED + 12), line_lens, page_nl)
        c_, p_, l_, b_, _ = flatten(gp, lambda w: w)
        rw = repetition(c_, p_, l_, 200, SEED)[1]["Rw"]
        fit_rows.append((abs(rw - target_rw), a, rw))
    best = min(fit_rows)
    emit(f"\n=== G_linepool fit: target R_within(1) ZL3b cut (200 shuffles) {target_rw:.3f}; grid " +
         "; ".join(f"alpha {a} -> {rw:.3f}" for _, a, rw in fit_rows) + f" -> alpha {best[1]}")
    texts.append(("G_linepool", "G", True, layout(None, True, gen(best[1], SEED + 12), line_lens, page_nl), "id", False,
                  f"line-pool generator (ZL3b page pools; alpha {best[1]} fitted to R_within(1))"))
    held["G_linepool"] = prepared_held_out("G_linepool", texts[-1][3], "id")
    n_match = min(held.values())
    emit(f"N_match (order) = {n_match} held-out tokens (smallest over gating texts and VOY)")
    emit("\n=== corpus list (class, gating, tokens after cut, held-out tokens, label) ===")
    for name, cls, gating, pages, sk, sec, lab in texts:
        nt = sum(len(ln) for _, ls in pages for ln in ls)
        emit(f"  {name:24s} {cls:3s} {'gating' if gating else ('target' if cls == 'VOY' else 'descriptive'):11s} "
             f"tokens {nt:6d} pages {len(pages):4d} held-out {held.get(name, '-')!s:>5s}  {lab}")
    flush()

    # ---- profiles
    P1, P2 = OrderedDict(), OrderedDict()
    emit("\n=== profiles (primary cores) ===")
    for i, (name, cls, gating, pages, sk, sec, lab) in enumerate(texts):
        P1[name] = profile(name, pages, sk, n_match, SEED + 100 * i, interval=(cls == "VOY"))
        P1[name]["cls"] = cls; P1[name]["gating"] = gating
        emit(f"  {name}: done [{P1[name]['secs']:.0f}s]")
        flush()
        if sec:
            P2[name] = profile(name + "/stem", pages, "slot", n_match, SEED + 100 * i + 50)
            P2[name]["cls"] = cls
    voy = [P1[f"VOY_{T}"] for T in ("ZL3b", "RF1b", "IT2a")]
    lb = loc_band_from(voy)
    rw_v = float(np.mean([p["rep"][1]["Rw"] for p in voy])); rc_v = float(np.mean([p["rep"][1]["Rc"] for p in voy]))
    emit(f"\nLOCALITY band (rule frozen; computed from VOY): [{lb[0]:.4f}, {lb[1]:.4f}]; "
         + "; ".join(f"{p['name']} {p['loc']['ratio']:.4f} [{p['loc']['lo']:.4f},{p['loc']['hi']:.4f}]" for p in voy))
    emit(f"ORDER bands: K100 [{ORDER_BAND[100][0]:+.4f},{ORDER_BAND[100][1]:+.4f}]  K200 [{ORDER_BAND[200][0]:+.4f},{ORDER_BAND[200][1]:+.4f}]")
    emit(f"R_VOY (mean of 3): R_within(1) {rw_v:.3f}, R_cross(1) {rc_v:.3f}")
    for p in voy:
        emit(f"  {p['name']} order 95 % (s80-style, {FX_INT_DRAWS} draws x 20): " +
             "; ".join(f"K{K} {p['order'][K]['mm']:+.3f}[{p['order'][K]['ci'][0]:+.3f},{p['order'][K]['ci'][1]:+.3f}]" for K in KS))

    emit("\n=== per-text profile table (C1 flags: a order, b R_within, c R_cross<R_within, d locality) ===")
    D = {}
    for name, p in P1.items():
        D[name] = distance(p, lb, rw_v, rc_v)
        emit("  " + fmt_prof(p, lb) + f" | D {D[name][0]:.2f} [{p['cls']}{'' if p['gating'] or p['cls'] == 'VOY' else ', descriptive'}]")
    emit("\n=== secondary: SlotSegmenter stems for natural texts (not in C2) ===")
    for name, p in P2.items():
        emit("  " + fmt_prof(p, lb) + f" | D {distance(p, lb, rw_v, rc_v)[0]:.2f}")
    flush()

    # ---- validity
    emit("\n=== validity (not gating) ===")
    v1 = []
    for p in voy:
        ok, comp = c1(p, lb)
        if not ok:
            v1.append(f"{p['name']}: " + ",".join(k for k, v in comp.items() if not v))
        emit(f"  V1 {p['name']} self-check C1: {'PASS' if ok else 'FAIL'} {dict(comp)}")
    for T in ("ZL3b", "RF1b", "IT2a"):
        Tp = S80.prepare(f"VOY_{T}", "VOY", [(p["id"], p["lines"]) for p in S80.S55.voynich_pages(T)], SlotSegmenter)
        ms = S80.matched_set(Tp, 6195)
        oc, olid, _ = S80.arrays(ms)
        labs = [S80.apply_map(oc, S80.fit_freq(Tp["tr_counts"], K)) for K in (100, 200)]
        r = order_excess(labs, olid, 200, SEED + 900)
        s = [vals[(f"VOY_{T}", K)][0] for K in (100, 200)]
        ok = all(abs(a[0] - b) < 0.006 for a, b in zip(r, s))
        emit(f"  V2 {T} s80 setting: K100 {r[0][0]:+.4f} (s80 {s[0]:+.4f}) K200 {r[1][0]:+.4f} (s80 {s[1]:+.4f}) -> {'PASS' if ok else 'FAIL'}")
        if T == "ZL3b":
            pc, mc = S80.mi_batch(labs[0][None, :-1], labs[0][None, 1:], int(labs[0].max()) + 1)
            pg_, mg = mi_mm_t(torch.as_tensor(labs[0][None, :-1], device=DEV), torch.as_tensor(labs[0][None, 1:], device=DEV),
                              int(labs[0].max()) + 1)
            emit(f"  V3 GPU MI == S80.mi_batch: {'PASS' if abs(float(mc[0]) - float(mg[0])) < 1e-9 else 'FAIL'}")
    flush()

    # ---- calls
    emit("\n=== C1 / C2 ===")
    like = OrderedDict()
    for name, p in P1.items():
        if not p["gating"]:
            continue
        ok, comp = c1(p, lb)
        like[name] = ok
        emit(f"  C1 {name:24s} {p['cls']}  {'VOYNICH-LIKE' if ok else 'no'}  fails: {', '.join(k for k, v in comp.items() if not v) or '-'}")
    c2 = OrderedDict((cls, sum(1 for n, ok in like.items() if ok and P1[n]["cls"] == cls)) for cls in ("L", "P", "V", "G"))
    ntot = OrderedDict((cls, sum(1 for n in like if P1[n]["cls"] == cls)) for cls in ("L", "P", "V", "G"))
    emit("  C2 Voynich-like per class: " + "; ".join(f"{c} {c2[c]}/{ntot[c]}" for c in c2))
    hit = [c for c in c2 if c2[c] > 0]
    if not hit:
        best_n = min((n for n in like), key=lambda n: D[n][0])
        cls_best = OrderedDict((c, min((D[n][0], n) for n in like if P1[n]["cls"] == c)) for c in ("L", "P", "V", "G"))
        cbest = min(cls_best, key=lambda c: cls_best[c][0])
        tn = cls_best[cbest][1]
        fails = [k for k, v in c1(P1[tn], lb)[1].items() if not v]
        reading = (f"no reference class reproduces the core layer; closest class {cbest} (text {tn}, D {cls_best[cbest][0]:.2f}), "
                   f"failing component(s): {', '.join(fails)}")
        emit("  class minimum D: " + "; ".join(f"{c} {v[0]:.2f} ({v[1]})" for c, v in cls_best.items()))
    elif any(c in hit for c in ("P", "V")):
        reading = "core profile is not genre-specific: classes with Voynich-like texts: " + ", ".join(f"{c} ({c2[c]})" for c in hit)
    elif hit == ["L"]:
        reading = "core layer behaves like list-genre content"
    elif hit == ["G"]:
        reading = "core layer behaves like a pool generator"
    else:
        reading = "list content and pool generators both reproduce it (not separated)"
    if v1:
        reading += f" [target self-check failed: {'; '.join(v1)}]"
    emit(f"\nVERDICT: {reading}")

    RUN_DIR.mkdir(parents=True, exist_ok=True)
    with (RUN_DIR / "profiles.csv").open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["text", "cores", "class", "gating", "tokens", "types", "o25", "o50", "o100", "p100", "o200", "p200", "o400",
                    "Rw1", "pRw1", "Rw2", "Rw3", "Rw4", "Rw5", "Rc1", "loc", "loc_lo", "loc_hi", "loc_p", "type_ratio", "C1", "D"])
        for tag, PP in (("primary", P1), ("stem", P2)):
            for name, p in PP.items():
                o = p["order"]; r = p["rep"]; l = p["loc"]
                w.writerow([name, tag, p["cls"], p.get("gating", False), p["tokens"], p["types"]] +
                           [f"{o[K]['mm']:.6f}" for K in (25, 50, 100)] + [f"{o[100]['p']:.4f}", f"{o[200]['mm']:.6f}", f"{o[200]['p']:.4f}",
                                                                           f"{o[400]['mm']:.6f}"] +
                           [f"{r[1]['Rw']:.4f}", f"{r[1]['pw']:.4f}"] +
                           [f"{r[d]['Rw']:.4f}" for d in (2, 3, 4, 5)] + [f"{r[1]['Rc']:.4f}"] +
                           [f"{l['ratio']:.4f}", f"{l['lo']:.4f}", f"{l['hi']:.4f}", f"{l['p_low']:.4f}", f"{l['type_ratio']:.4f}",
                            c1(p, lb)[0], f"{distance(p, lb, rw_v, rc_v)[0]:.3f}"])
    (RUN_DIR / "calls.json").write_text(json.dumps(dict(n_match=n_match, loc_band=lb, order_band=ORDER_BAND, rw_v=rw_v, rc_v=rc_v,
                                                        linepool_alpha=best[1], C1=like, C2=c2, verdict=reading), indent=1),
                                        encoding="utf-8", newline="\n")
    emit(f"\nsidecars: runs/s87/profiles.csv, runs/s87/calls.json")
    emit(f"runtime {time.time() - T0:.0f} s; finished {clock()}")
    flush()


