class LP91:
    """Line-scoped core producer.  glob: {core: weight} (training lexicon); bigram: {prev: Counter(next)}."""

    def __init__(self, glob, bigram):
        items = sorted(c for c, v in glob.items() if c != "" and v > 0)
        idx = {c: i for i, c in enumerate(items)}
        self.items = items
        g = np.array([float(glob[c]) for c in items])
        self.g = g / g.sum()
        self.succ = []
        for c in items:
            row = bigram.get(c)
            self.succ.append({idx[d]: float(n) for d, n in row.items() if d in idx} if row else {})
        self.p = dict(START)

    def set_params(self, p):
        self.p = dict(p)

    def lexicon(self, seed, j):
        rng = np.random.default_rng([seed, j])
        x = rng.gamma(self.p["conc"] * self.g)
        s = float(x.sum())
        if not np.isfinite(s) or s <= 0:
            return self.g.copy()
        return x / s

    def page(self, rng, w, lens):
        succ = self.succ
        a, lam, rho, pen = self.p["alpha"], self.p["lam"], self.p["rho"], self.p["pen"]
        nI = len(self.items)
        logw = np.full(nI, -np.inf)
        nz = w > 0
        logw[nz] = 0.5 * np.log(w[nz])   # REVISION 1: pool draws proportional to sqrt(w_q)
        lpen = math.log(1.0 - pen) if pen < 1.0 else -np.inf
        prev = None
        out = []
        for n in lens:
            if n <= 0:
                continue
            lw = logw
            if prev is not None and pen > 0:
                lw = logw.copy()
                lw[prev] += lpen
                if not np.isfinite(lw).any():
                    lw = logw
            navail = int(np.isfinite(lw).sum())
            k = min(navail, max(1, int(round(a * n))))
            key = lw + rng.gumbel(size=nI)
            pool = np.argpartition(-key, k - 1)[:k] if k < nI else np.arange(nI)
            sw = np.sqrt(w[pool]); f = sw / sw.sum()   # REVISION 1: emission proportional to sqrt(w_q) within the pool
            line = []
            for i in range(n):
                if i > 0 and rho > 0 and rng.random() < rho:
                    c = line[int(rng.integers(i))]
                else:
                    pr = f
                    if i > 0 and lam > 0:
                        row = succ[line[-1]]
                        if row:
                            t = np.array([row.get(int(j), 0.0) for j in pool])
                            s = t.sum()
                            if s > 0:
                                pr = (1.0 - lam) * f + lam * t / s
                    cs = np.cumsum(pr)
                    c = int(pool[min(k - 1, int(np.searchsorted(cs, rng.random() * cs[-1], side="right")))])
                line.append(c)
            prev = np.array(sorted(set(line)), dtype=np.int64)
            out.append(line)
        return out

    def text(self, spec, seed, tag=None, cipher=None, seg=None):
        """spec: list of (pid, quire, [line lengths]) -> core pages [(id, lines)]; with cipher (word pages aligned to
        spec) and seg: also word pages (prefix + core + suffix, slots of the cipher word)."""
        qidx, lex = {}, {}
        cp, wp = [], []
        for pi, (pid, q, lens) in enumerate(spec):
            if q not in qidx:
                qidx[q] = len(qidx)
                lex[q] = self.lexicon(seed, qidx[q])
            rng = np.random.default_rng([seed, 1_000_000 + pi])
            lines = self.page(rng, lex[q], lens)
            cl = [[self.items[c] for c in ln] for ln in lines]
            name = f"{tag}:{pid}" if tag is not None else pid
            cp.append((name, cl))
            if cipher is not None:
                wl = []
                for ln, cln in zip(cl, cipher[pi]):
                    ws = []
                    for c, cw in zip(ln, cln):
                        pre, _, suf = seg.segment(cw)
                        ws.append(pre + c + suf)
                    wl.append(ws)
                wp.append((name, wl))
        return (cp, wp) if cipher is not None else cp


def bigram_of(core_pages):
    B = defaultdict(Counter)
    for _, lines in core_pages:
        for ln in lines:
            for a, b in zip(ln[:-1], ln[1:]):
                B[a][b] += 1
    return B


