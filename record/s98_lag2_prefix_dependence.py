# ============================================================ numba kernels
@njit(cache=False)
def _cmi(R, lens, cmap, K):
    """Miller-Madow CMI I(A;C|B) over within-line triples of lumped classes, bits."""
    nabc = np.zeros(K * K * K, np.int64)
    nl = R.shape[0]
    N = 0
    for l in range(nl):
        L = lens[l]
        for j in range(L - 2):
            a = cmap[R[l, j]]
            b = cmap[R[l, j + 1]]
            c = cmap[R[l, j + 2]]
            nabc[(a * K + b) * K + c] += 1
            N += 1
    if N == 0:
        return np.nan
    nab = np.zeros(K * K, np.int64)
    nbc = np.zeros(K * K, np.int64)
    nb = np.zeros(K, np.int64)
    for a in range(K):
        for b in range(K):
            for c in range(K):
                v = nabc[(a * K + b) * K + c]
                if v:
                    nab[a * K + b] += v
                    nbc[b * K + c] += v
                    nb[b] += v
    return _hmm(nab, N) + _hmm(nbc, N) - _hmm(nb, N) - _hmm(nabc, N)


@njit(cache=False)
def _hmm(cnt, N):
    h = 0.0
    m = 0
    for v in cnt:
        if v > 0:
            p = v / N
            h -= p * math.log(p)
            m += 1
    return (h + (m - 1) / (2.0 * N)) / math.log(2.0)


@njit(cache=False)
def _xcmi(R, lens, cmap, K, w):
    s = 0.0
    n = 0
    for l in range(R.shape[0]):
        for j in range(lens[l] - 2):
            s += w[(cmap[R[l, j]] * K + cmap[R[l, j + 1]]) * K + cmap[R[l, j + 2]]]
            n += 1
    return s / n if n else np.nan


@njit(cache=False)
def _stats(R, lens, cmaps, Ks, W, out):
    nk = Ks.shape[0]
    for k in range(nk):
        out[k] = _xcmi(R, lens, cmaps[k], Ks[k], W[k])
        out[nk + k] = _cmi(R, lens, cmaps[k], Ks[k])


@njit(cache=False)
def _run(R, Kk, lens, gid, gs, ge, maxL, steps):
    nl = R.shape[0]
    for _ in range(steps):
        l1 = np.random.randint(nl)
        g = gid[l1]
        ng = ge[g] - gs[g]
        if ng < 2:
            continue
        i = 1 + np.random.randint(maxL - 1)
        if i >= lens[l1]:
            continue
        l2 = gs[g] + np.random.randint(ng - 1)
        if l2 >= l1:
            l2 += 1
        if i >= lens[l2]:
            continue
        if Kk[l1, i] != Kk[l2, i]:
            continue
        for j in range(i):
            t = R[l1, j]
            R[l1, j] = R[l2, j]
            R[l2, j] = t
            t = Kk[l1, j]
            Kk[l1, j] = Kk[l2, j]
            Kk[l2, j] = t


@njit(cache=False)
def _null(R0, K0, lens, gid, gs, ge, maxL, steps, M, seed, cmaps, Ks, W):
    """Besag-Clifford parallel: hub = B steps from observed; M runs of B steps from the hub."""
    np.random.seed(seed)
    nk = Ks.shape[0]
    R = R0.copy()
    Kk = K0.copy()
    _run(R, Kk, lens, gid, gs, ge, maxL, steps)
    Rh = R.copy()
    Kh = Kk.copy()
    out = np.empty((M, 2 * nk))
    for m in range(M):
        R = Rh.copy()
        Kk = Kh.copy()
        _run(R, Kk, lens, gid, gs, ge, maxL, steps)
        _stats(R, lens, cmaps, Ks, W, out[m])
    return out


def xweights(train_lines, cmap, K):
    """Cross-fit weights (w_f + w_b) / 2 from training triples (raw symbol ids), flat (a, b, c) index."""
    n = np.zeros((K, K, K))
    for l in train_lines:
        for j in range(len(l) - 2):
            n[cmap[l[j]], cmap[l[j + 1]], cmap[l[j + 2]]] += 1
    nbc = n.sum(0)
    nab = n.sum(2)
    p0 = (n.sum((0, 1)) + 0.5) / (n.sum() + 0.5 * K)
    p1f = (nbc + BETA * p0[None, :]) / (nbc.sum(1)[:, None] + BETA)                 # P1(c|b) [b, c]
    p2f = (n + BETA * p1f[None, :, :]) / (nab[:, :, None] + BETA)                     # P2(c|a,b) [a, b, c]
    wf = np.log2(p2f) - np.log2(p1f)[None, :, :]
    q0 = (n.sum((1, 2)) + 0.5) / (n.sum() + 0.5 * K)
    p1b = (nab + BETA * q0[:, None]) / (nab.sum(0)[None, :] + BETA)                  # P1(a|b) [a, b]
    p2b = (n + BETA * p1b[:, :, None]) / (nbc[None, :, :] + BETA)                     # P2(a|b,c) [a, b, c]
    wb = np.log2(p2b) - np.log2(p1b)[:, :, None]
    return (0.5 * (wf + wb)).ravel()


def null_test(lines, keys, line_page, cmaps, Ks, mode, seed, train_lines):
    """lines: list of lists of int raw symbols; keys: matching keys (same shape); returns obs[2k], null[M,2k]
    (first k = XCMI at Ks, next k = MMCMI at Ks)."""
    order = list(range(len(lines)))
    if mode in ("len", "word"):
        grp = [len(l) for l in lines]
    elif mode == "page":
        grp = list(line_page)
    else:
        raise ValueError(mode)
    order.sort(key=lambda i: (grp[i], i))
    nl = len(lines)
    maxL = max(2, max(len(l) for l in lines))
    R = np.zeros((nl, maxL), np.int64)
    Kk = np.zeros((nl, maxL), np.int64)
    lens = np.zeros(nl, np.int64)
    gid = np.zeros(nl, np.int64)
    gs, ge, gmap = [], [], {}
    for r, i in enumerate(order):
        g = grp[i]
        if g not in gmap:
            gmap[g] = len(gs)
            gs.append(r)
            ge.append(r)
        ge[gmap[g]] = r + 1
        gid[r] = gmap[g]
        lens[r] = len(lines[i])
        R[r, :len(lines[i])] = lines[i]
        Kk[r, :len(lines[i])] = keys[i]
    ntok = int(lens.sum())
    steps = STEPS_PER_TOKEN * ntok
    Ks_a = np.array(Ks, np.int64)
    cm = np.zeros((len(Ks), max(int(c.shape[0]) for c in cmaps)), np.int64)
    for k, c in enumerate(cmaps):
        cm[k, :c.shape[0]] = c
    W = np.zeros((len(Ks), max(Ks) ** 3))
    for k, c in enumerate(cmaps):
        W[k, :Ks[k] ** 3] = xweights(train_lines, c, Ks[k])
    obs = np.empty(2 * len(Ks))
    _stats(R, lens, cm, Ks_a, W, obs)
    nul = _null(R, Kk, lens, gid, np.array(gs, np.int64), np.array(ge, np.int64), maxL, steps, M_NULL, seed, cm, Ks_a, W)
    return obs, nul


def summarize_test(obs, nul):
    out = []
    for k in range(len(obs)):
        o = float(obs[k])
        n = nul[:, k]
        p = (1 + int(np.sum(n >= o - 1e-12))) / (len(n) + 1)
        out.append(dict(obs=o, null_mean=float(np.mean(n)), null_sd=float(np.std(n)), excess=o - float(np.mean(n)),
                        p=p, pos=bool(o - float(np.mean(n)) > 0 and p < ALPHA)))
    return out


# ============================================================ measurement of one text on one fold
def class_map(train_counts: Counter, alphabet: dict, K: int):
    top = [s for s, _ in sorted(train_counts.items(), key=lambda kv: (-kv[1], str(kv[0])))]
    cm = np.zeros(len(alphabet), np.int64)
    if len(top) <= K:
        rank = {s: i for i, s in enumerate(top)}
        nK = max(len(top), 1) + 1          # + unseen class
        for s, i in alphabet.items():
            cm[i] = rank.get(s, nK - 1)
        return cm, nK
    keep = {s: i for i, s in enumerate(top[:K - 1])}
    for s, i in alphabet.items():
        cm[i] = keep.get(s, K - 1)
    return cm, K


def measure(pages, Q, given=False, seed=0, slots=("pre", "suf")):
    """pages: list of (pid, quire, lines).  given=False: tokens are words (SlotSegmenter fitted on training quires);
    given=True: tokens are (prefix, suffix) tuples already.  Returns dict slot -> null -> list over K of results."""
    tr = [w for _, q, ls in pages if q != Q for l in ls for w in l]
    te_pages = [(pid, ls) for pid, q, ls in pages if q == Q]
    if given:
        seg = lambda w: w  # noqa: E731
    else:
        sg = SlotSegmenter(tr)
        cache = {}

        def seg(w):
            v = cache.get(w)
            if v is None:
                pr, _, su = sg.segment(w)
                v = cache[w] = (pr or EMPTY, su or EMPTY)
            return v
    res = {"n_lines": sum(len(ls) for _, ls in te_pages), "n_tok": sum(len(l) for _, ls in te_pages for l in ls)}
    tr_ps = [seg(w) for w in tr]
    tr_lines = [[seg(w) for w in l] for _, q, ls in pages if q != Q for l in ls]
    te_lines, te_page = [], []
    for pi, (pid, ls) in enumerate(te_pages):
        for l in ls:
            te_lines.append([seg(w) for w in l])
            te_page.append(pi)
    res["n_triples"] = sum(max(0, len(l) - 2) for l in te_lines)
    for si, slot in enumerate(("pre", "suf")):
        if slot not in slots:
            continue
        alph = {}
        for ps in tr_ps:
            alph.setdefault(ps[si], len(alph))
        for l in te_lines:
            for ps in l:
                alph.setdefault(ps[si], len(alph))
        pairs = {}
        for l in te_lines:
            for ps in l:
                pairs.setdefault(ps, len(pairs))
        cnt = Counter(ps[si] for ps in tr_ps)
        cmaps, Ks = [], []
        for K in (K_MAIN,) + K_DESC:
            cm, nK = class_map(cnt, alph, K)
            cmaps.append(cm)
            Ks.append(nK)
        raw = [[alph[ps[si]] for ps in l] for l in te_lines]
        traw = [[alph[ps[si]] for ps in l] for l in tr_lines]
        out = {"K": Ks, "inventory": len(cnt), "stats": [f"XCMI_K{k}" for k in Ks] + [f"MMCMI_K{k}" for k in Ks]}
        for ni, mode in enumerate(NULLS_PRE if slot == "pre" else NULLS_SUF):
            keys = [[pairs[ps] for ps in l] for l in te_lines] if mode == "word" else raw
            obs, nul = null_test(raw, keys, te_page, cmaps, Ks, mode, seed + 1009 * si + 101 * ni, traw)
            out[mode] = summarize_test(obs, nul)
        res[slot] = out
    return res


