def replicate_to_ntot(make, first_seed):
    pages, tot, j = [], 0, 0
    while tot < N_TOT:
        P = make(first_seed + j, j)
        pages.extend(P)
        tot += sum(len(ln) for _, ls in P for ln in ls)
        j += 1
        if j > 400:
            break
    return cut(pages), j


def fit_lp(prod, spec_tr, target, seed):
    """REVISION 2: candidate statistics averaged over FIT_SEEDS generated texts; coordinate descent from each of
    STARTS, the lower final loss kept (ties -> first start)."""
    set_counts(FIT_COUNTS)
    cache = {}

    def ev(prm):
        key = tuple(prm[k] for k in KEYS)
        if key not in cache:
            prod.set_params(prm)
            gs = [comps(S87.profile("fit", own(prod.text(spec_tr, fs)), "id", N_MATCH, seed + fs)) for fs in FIT_SEEDS]
            g = {k: float(np.mean([x[k] for x in gs])) for k in gs[0]}
            cache[key] = (fit_loss(g, target), g, dict(prm))
        return cache[key]
    runs = []
    for st in STARTS:
        best = ev(dict(st))
        sweeps = 0
        for _ in range(MAX_SWEEPS):
            sweeps += 1
            improved = False
            for k in SWEEP:
                for v in GRID[k]:
                    r = ev(dict(best[2], **{k: v}))
                    if r[0] < best[0] - 1e-12:
                        best = r; improved = True
            if not improved:
                break
        runs.append((best, sweeps))
    best, sweeps = min(runs, key=lambda x: x[0][0])
    set_counts(FULL_COUNTS)
    prod.set_params(best[2])
    return dict(params=best[2], loss=best[0], gen=best[1], n_evals=len(cache), sweeps=sweeps,
                start_losses=[round(r[0][0], 4) for r in runs])


