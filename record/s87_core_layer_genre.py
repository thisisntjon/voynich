def tokens_norm(s, min_len=1):
    s = unicodedata.normalize("NFD", s)
    s = "".join(ch for ch in s if unicodedata.category(ch) != "Mn").lower()
    return [t for t in re.findall(r"[^\W\d_]+", s) if len(t) >= min_len]


def layout(lines_or_tokens, real_lines, pages_given, line_lens, page_nl, n_tot=N_TOT):
    """-> list of (page_id, lines) cut to n_tot tokens; pages_given: list of (id, lines) (real pages) or None."""
    if pages_given is not None:
        out, tot = [], 0
        for pid, lines in pages_given:
            if tot >= n_tot:
                break
            L = []
            for ln in lines:
                ln = [w for w in ln if w]
                if not ln:
                    continue
                if tot >= n_tot:
                    break
                take = ln[:n_tot - tot]
                L.append(take); tot += len(take)
            if L:
                out.append((str(pid), L))
        return out
    if real_lines:
        lines = [[w for w in ln if w] for ln in lines_or_tokens]
        lines = [ln for ln in lines if ln]
    else:
        toks = list(lines_or_tokens)
        lines, i, j = [], 0, 0
        while i < len(toks):
            n = line_lens[j % len(line_lens)]; j += 1
            lines.append(toks[i:i + n]); i += n
    cut, tot = [], 0
    for ln in lines:
        if tot >= n_tot:
            break
        take = ln[:n_tot - tot]
        cut.append(take); tot += len(take)
    pages, i, j = [], 0, 0
    while i < len(cut):
        n = page_nl[j % len(page_nl)]
        pages.append((f"p{j:04d}", cut[i:i + n])); i += n; j += 1
    return pages


def flatten(pages, core_of):
    """-> cores (int, -1 empty), page ids, global line ids, block ids, core vocabulary."""
    ids = {}
    cores, pg, ln_id, blk = [], [], [], []
    tok = 0; li = 0
    ntot = sum(len(ln) for _, ls in pages for ln in ls)   # = N_TOT for gating texts (block = 1,500 tokens)
    for pi, (_, lines) in enumerate(pages):
        b = min(NB - 1, tok * NB // ntot)
        for ln in lines:
            for w in ln:
                c = core_of(w)
                cores.append(-1 if c == "" else ids.setdefault(c, len(ids)))
                pg.append(pi); ln_id.append(li); blk.append(b); tok += 1
            li += 1
    return np.array(cores), np.array(pg), np.array(ln_id), np.array(blk), ids


