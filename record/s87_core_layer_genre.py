def locality(cores, block, n_perm, n_boot, seed, chunk=50):
    cores = np.asarray(cores); block = np.asarray(block)
    keep = cores >= 0
    c = S80.compact(cores[keep]); b = block[keep]
    V = int(c.max()) + 1
    c_t = torch.as_tensor(c, device=DEV, dtype=torch.long); b_t = torch.as_tensor(b, device=DEV, dtype=torch.long)

    def cov_types(C, S):  # C: (S, n) -> coverage (S, NB), types (S, NB)
        off = torch.arange(S, device=DEV, dtype=torch.long)[:, None]
        idx = (off * NB + b_t[None, :]) * V + C
        pres = torch.bincount(idx.reshape(-1), minlength=S * NB * V).reshape(S, NB, V) > 0
        cnt = pres.sum(1, keepdim=True)
        cov = (pres & ((cnt - pres.long()) > 0)).sum(2).double()
        typ = pres.sum(2).double()
        return cov / torch.clamp(typ, min=1), typ
    cov_o, typ_o = cov_types(c_t[None], 1)
    cov_o = cov_o[0].cpu().numpy(); typ_o = typ_o[0].cpu().numpy()
    gen = torch.Generator(device=DEV).manual_seed(seed)
    covs, typs = [], []
    done = 0
    while done < n_perm:
        S = min(chunk, n_perm - done)
        P = torch.argsort(torch.rand((S, c_t.numel()), generator=gen, device=DEV), dim=1)
        cv, ty = cov_types(c_t[P], S)
        covs.append(cv); typs.append(ty)
        done += S
    cov_n = torch.cat(covs).cpu().numpy(); typ_n = torch.cat(typs).cpu().numpy()
    null_b = cov_n.mean(0)
    ratio = float(cov_o.mean() / null_b.mean())
    p_low = (1 + int((cov_n.mean(1) <= cov_o.mean()).sum())) / (1 + cov_n.shape[0])
