# ============================================================ summary
def fold_counts(allres, Ts, folds_by_T, slot, text, null="len", ki=0):
    out = {}
    for T in Ts:
        c = 0
        for Q in folds_by_T[T]:
            r = allres[(T, Q)]["texts"].get(text)
            if r and r[slot][null][ki]["pos"]:
                c += 1
        out[T] = c
    return out


def reading_of(allres, Ts, folds_by_T, slot):
    cv = fold_counts(allres, Ts, folds_by_T, slot, "VOY")
    cs = fold_counts(allres, Ts, folds_by_T, slot, "S81")
    cf = fold_counts(allres, Ts, folds_by_T, slot, "FO")
    call_voy = all(cv[T] >= N_NEED for T in Ts)
    call_s81 = all(cs[T] >= N_NEED for T in Ts)
    call_fo = all(cf[T] < N_NEED for T in Ts)
    voy_none = all(cv[T] < N_NEED for T in Ts)
    if call_voy and call_s81 and call_fo:
        rd = "H-14-like (hidden line state)"
    elif voy_none and call_s81 and call_fo:
        rd = "H-05-like (first-order cursor)"
    else:
        rd = "inconclusive"
    return dict(cv=cv, cs=cs, cf=cf, CALL_VOY=call_voy, CALL_S81=call_s81, CALL_FO=call_fo, VOY_NONE=voy_none,
                reading=rd)


def report(allres, Ts, folds_by_T):
    for slot in ("pre", "suf"):
        emit(f"=== PER-FOLD TABLE: {'PREFIX' if slot == 'pre' else 'SUFFIX'} XCMI (K={K_MAIN}, same-length null; "
             f"excess bits x1000 / exact p; * = positive: excess > 0 and p < {ALPHA}) ===")
        for T in Ts:
            emit(f"  {T}:")
            emit(f"    {'fold':4} {'lines':>5} {'trip':>5}  " + "  ".join(f"{t:>15}" for t in TEXTS) + "   S81 p_fit")
            for Q in folds_by_T[T]:
                r = allres[(T, Q)]
                cells = []
                for t in TEXTS:
                    x = r["texts"].get(t)
                    if not x:
                        cells.append(f"{'n/a':>15}")
                        continue
                    c = x[slot]["len"][0]
                    cells.append(f"{1000 * c['excess']:+7.2f}/{c['p']:.3f}{'*' if c['pos'] else ' '}")
                v = r["texts"]["VOY"]
                emit(f"    {Q:4} {v['n_lines']:>5} {v['n_triples']:>5}  " + "  ".join(cells) + f"   {r.get('s81_p')}")
            cnt = {t: fold_counts(allres, [T], folds_by_T, slot, t)[T] for t in TEXTS}
            emit(f"    positive folds: " + "  ".join(f"{t} {cnt[t]}/{len(folds_by_T[T])}" for t in TEXTS))
        emit("")
    emit(f"=== DESCRIPTIVE: positive-fold counts by estimator, K and null (prefix unless marked) ===")
    nk = 1 + len(K_DESC)
    for T in Ts:
        for ki, K in enumerate((K_MAIN,) + K_DESC):
            for est, off in (("XCMI", 0), ("MMCMI", nk)):
                emit(f"  {T} {est:5} K={K:<2} len : " + "  ".join(f"{t} {fold_counts(allres, [T], folds_by_T, 'pre', t, 'len', off + ki)[T]:>2}" for t in TEXTS))
        for null in ("page", "word"):
            for est, off in (("XCMI", 0), ("MMCMI", nk)):
                emit(f"  {T} {est:5} K={K_MAIN:<2} {null:4}: " + "  ".join(f"{t} {fold_counts(allres, [T], folds_by_T, 'pre', t, null, off)[T]:>2}" for t in TEXTS))
        for est, off in (("XCMI", 0), ("MMCMI", nk)):
            emit(f"  {T} {est:5} K={K_MAIN:<2} len  SUFFIX: " + "  ".join(f"{t} {fold_counts(allres, [T], folds_by_T, 'suf', t, 'len', off)[T]:>2}" for t in TEXTS))
    emit("")
    emit("=== EXCESS SIZE (XCMI, median over folds, bits x1000; K_MAIN, same-length null) and VOY / S81 ratio ===")
    ratios = {}
    for slot in ("pre", "suf"):
        for T in Ts:
            med = {}
            for t in TEXTS:
                v = [allres[(T, Q)]["texts"][t][slot]["len"][0]["excess"] for Q in folds_by_T[T] if t in allres[(T, Q)]["texts"]]
                med[t] = float(np.median(v)) if v else float("nan")
            ratio = med["VOY"] / med["S81"] if med["S81"] not in (0.0,) and not math.isnan(med["S81"]) else float("nan")
            ratios[(slot, T)] = ratio
            emit(f"  {slot} {T}: " + "  ".join(f"{t} {1000 * med[t]:+.3f}" for t in TEXTS) + f"   VOY/S81 {ratio:+.2f}")
    emit("")
    return ratios


