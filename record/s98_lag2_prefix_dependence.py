def load_real(T):
    path = ROOT / "data" / "translit" / f"{TRANSLITS[T]}.meta.json"
    pages = S67.load_pages(path)
    d = json.loads(path.read_text(encoding="utf-8"))
    hands = {str(p["id"]): str(p.get("hand", "?")) for p in d["pages"]}
    return path, pages, hands


def fixture_skeleton(seed):
    r = random.Random(seed)
    sizes = [r.randint(70, 300) for _ in range(14)] + [800]
    r.shuffle(sizes)
    pages = []
    for qi, n in enumerate(sizes):
        q = "ABCDEFGHIJKLMNO"[qi]
        k = 0
        left = n
        while left > 0:
            m = min(left, r.randint(8, 16))
            pages.append((f"x{q}{k:02d}", q, [r.randint(2, 13) for _ in range(m)]))
            left -= m
            k += 1
    return pages


def fixture_chain(kind, seed, nsym=20):
    """kind 'fo' first-order (final-aware) or 'ls' line-state; returns pages of (sym, '∅') tuples."""
    rng = np.random.default_rng(seed)
    skel = fixture_skeleton(seed)
    base = rng.dirichlet(np.full(nsym, 1.0))
    if kind == "fo":
        init = 0.5 * base + 0.5 * rng.dirichlet(np.full(nsym, 0.5))
        T0 = np.array([0.55 * base + 0.45 * rng.dirichlet(np.full(nsym, 0.3)) for _ in range(nsym)])
        T1 = np.array([0.4 * base + 0.6 * rng.dirichlet(np.full(nsym, 0.3)) for _ in range(nsym)])
    else:
        tabs = np.array([0.05 * base + 0.95 * rng.dirichlet(np.full(nsym, 0.3)) for _ in range(4)])
    out = []
    for pid, q, lens in skel:
        ls = []
        for L in lens:
            if kind == "fo":
                x = [rng.choice(nsym, p=init)]
                for j in range(1, L):
                    x.append(rng.choice(nsym, p=(T1 if j == L - 1 else T0)[x[-1]]))
            else:
                z = rng.integers(4)
                x = []
                for j in range(L):
                    if j > 0 and rng.random() >= 0.75:
                        z = rng.integers(4)
                    x.append(rng.choice(nsym, p=tabs[z]))
            ls.append([(f"s{v}", EMPTY) for v in x])
        out.append((pid, q, ls))
    return out


def fixture_a_job(job):
    lower_priority()
    pages = fixture_chain(job["kind"], job["seed"])
    folds = sorted({q for _, q, _ in pages})
    rows = []
    for fi, Q in enumerate(folds):
        r = measure(pages, Q, given=True, seed=job["seed"] * 100 + fi, slots=("pre",))
        rows.append(dict(r["pre"]["len"][0], mm=r["pre"]["len"][1 + len(K_DESC)]))
    return dict(kind=job["kind"], seed=job["seed"], rows=rows)


