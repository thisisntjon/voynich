    bs = []
    for _ in range(n_boot):
        ix = rng.integers(NB, size=NB)
        bs.append(cov_o[ix].mean() / null_b[ix].mean())
    lo, hi = float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))
    return dict(ratio=ratio, lo=lo, hi=hi, p_low=p_low, cov_obs=float(cov_o.mean()), cov_null=float(null_b.mean()),
                type_ratio=float(typ_o.mean() / typ_n.mean()), V=V)


