def fo_generate(pages, Q, seed, real_seg_pairs):
    """First-order raw prefix chain and independent suffix chain, add-0.5, final-aware; full skeleton."""
    rng = np.random.default_rng(seed)
    tr_lines = [[real_seg_pairs[w] for w in l] for _, q, ls in pages if q != Q for l in ls]
    out_pages = []
    models = []
    for si in (0, 1):
        alph = sorted({ps[si] for l in tr_lines for ps in l}, key=str)
        ix = {s: i for i, s in enumerate(alph)}
        n = len(alph)
        init = np.full(n, 0.5)
        trans = np.full((2, n, n), 0.5)
        for l in tr_lines:
            init[ix[l[0][si]]] += 1
            for j in range(1, len(l)):
                trans[int(j == len(l) - 1), ix[l[j - 1][si]], ix[l[j][si]]] += 1
        init /= init.sum()
        trans /= trans.sum(axis=2, keepdims=True)
        models.append((alph, init, trans))
    for pid, q, ls in pages:
        nls = []
        for l in ls:
            L = len(l)
            seqs = []
            for alph, init, trans in models:
                n = len(alph)
                x = [rng.choice(n, p=init)]
                for j in range(1, L):
                    x.append(rng.choice(n, p=trans[int(j == L - 1), x[-1]]))
                seqs.append([alph[i] for i in x])
            nls.append(list(zip(seqs[0], seqs[1])))
        out_pages.append((pid, q, nls))
    return out_pages


def s81_generate(pages, Q):
    skel = [[len(l) for l in ls] for _, _, ls in pages]
    tr_idx = [i for i, (_, q, _) in enumerate(pages) if q != Q]
    fit = S81.fit_p(tr_idx, [pages[i][2] for i in tr_idx], skel, "line", "latin_cremma")
    full = S81.encipher(S81.plain_letters("latin_cremma"), S81.key_tables(), skel, "line", fit["p"],
                        seed=S81.gen_seed("line_sticky_fit", "latin_cremma", 1))
    return [(pid, q, full[i]) for i, (pid, q, _) in enumerate(pages)], fit


def wtg_generate(pages, hands, Q, seed):
    train_meta = [dict(lines=ls, hand=hands.get(pid, "?"), section="?", para=None) for pid, q, ls in pages if q != Q]
    tr_tok = [w for m in train_meta for l in m["lines"] for w in l]
    seg = SlotSegmenter(tr_tok)
    prod = S71.WTGProducer(train_meta, seg, S71.WTG_PARAMS)
    rng = random.Random(seed)
    out = []
    for pid, q, ls in pages:
        out.append((pid, q, prod.generate_page(rng, len(ls), hand="ALL", line_lens=[len(l) for l in ls])))
    return out


_LAT = {}


def latin_words():
    if "w" not in _LAT:
        d = json.loads((S81.S64.S49 / "lang_latin_cremma.meta.json").read_text(encoding="utf-8"))
        _LAT["w"] = [w for pg in d["pages"] for ln in pg["lines"] for w in ln if w]
    return _LAT["w"]


def latin_pour(pages):
    W = latin_words()
    k = 0
    out = []
    for pid, q, ls in pages:
        nls = []
        for l in ls:
            nls.append([W[(k + j) % len(W)] for j in range(len(l))])
            k += len(l)
        out.append((pid, q, nls))
    return out


def run_fold(job):
    lower_priority()
    t0 = time.time()
    T, Q, pages, hands, base = job["T"], job["Q"], job["pages"], job["hands"], job["seed"]
    res = dict(T=T, Q=Q, texts={})
    try:
        res["texts"]["VOY"] = measure(pages, Q, seed=base + 1)
        g81, fit = s81_generate(pages, Q)
        res["s81_p"] = fit["p"]
        res["texts"]["S81"] = measure(g81, Q, seed=base + 2)
        tr = [w for _, q, ls in pages if q != Q for l in ls for w in l]
        sg = SlotSegmenter(tr)
        allw = {w for _, _, ls in pages for l in ls for w in l}
        segp = {}
        for w in allw:
            pr, _, su = sg.segment(w)
            segp[w] = (pr or EMPTY, su or EMPTY)
        gfo = fo_generate(pages, Q, base + 3, segp)
        res["texts"]["FO"] = measure(gfo, Q, given=True, seed=base + 4)
        gw = wtg_generate(pages, hands, Q, base + 5)
        res["texts"]["WTG"] = measure(gw, Q, seed=base + 6)
        res["texts"]["LAT"] = measure(latin_pour(pages), Q, seed=base + 7)
    except Exception:
        res["error"] = traceback.format_exc()
    res["secs"] = time.time() - t0
    return res


