# ======================================================================= producer
class LP94(S91.LP91):
    """REVISION 1: s91's LP91 with one book-wide lexicon g and a random per-quire tilt: every quire (training,
    held-out, replicate alike) gets w_q = (1 - tilt) g + tilt d_q, d_q ~ Dirichlet(conc x g) drawn fresh per quire
    (LP91.lexicon: default_rng([seed, j]), j = order of first appearance in the text's spec)."""

    def __init__(self, glob, bigram):
        super().__init__(glob, bigram)
        self.p = dict(START)

    def lexicon_of(self, seed, j):
        m = self.p["tilt"]
        if m <= 0:
            return self.g.copy()
        d = self.lexicon(seed, j)   # s91: Dirichlet(conc x g) by gamma draws, normalised
        return (1.0 - m) * self.g + m * d

    def text(self, spec, seed, tag=None):
        lex = {}
        cp = []
        for pi, (pid, q, lens) in enumerate(spec):
            if q not in lex:
                lex[q] = self.lexicon_of(seed, len(lex))
            rng = np.random.default_rng([seed, 1_000_000 + pi])
            lines = self.page(rng, lex[q], lens)
            name = f"{tag}:{pid}" if tag is not None else pid
            cp.append((name, [[self.items[c] for c in ln] for ln in lines]))
        return cp


def fit_lp(prod, spec_tr, target, seed):
    """s91's fit (2-seed averaged candidate statistics, two starts), over this script's KEYS/GRID/STARTS."""
    S91.set_counts(S91.FIT_COUNTS)
    cache = {}

    def ev(prm):
        key = tuple(prm[k] for k in KEYS)
        if key not in cache:
            prod.set_params(prm)
            gs = [S91.comps(S87.profile("fit", S91.own(prod.text(spec_tr, fs)), "id", N_MATCH, seed + fs)) for fs in FIT_SEEDS]
            g = {k: float(np.mean([x[k] for x in gs])) for k in gs[0]}
            cache[key] = (S91.fit_loss(g, target), g, dict(prm))
        return cache[key]
    runs = []
    for st in STARTS:
        best = ev(dict(st))
        sweeps = 0
        for _ in range(MAX_SWEEPS):
            sweeps += 1
            improved = False
            for k in SWEEP:
                for v in GRID[k]:
                    r = ev(dict(best[2], **{k: v}))
                    if r[0] < best[0] - 1e-12:
                        best = r; improved = True
            if not improved:
                break
        runs.append((best, sweeps))
    best, sweeps = min(runs, key=lambda x: x[0][0])
    S91.set_counts(S91.FULL_COUNTS)
    prod.set_params(best[2])
    return dict(params=best[2], loss=best[0], gen=best[1], n_evals=len(cache), sweeps=sweeps,
                start_losses=[round(r[0][0], 4) for r in runs])


# ======================================================================= one LOQO fold (worker)
def wait_ram():
    """REVISION 1 memory guard: before each fold, wait (re-check every 60 s) while free RAM < MIN_FOLD_GB."""
    waited = 0
    while True:
        fg = free_gb()
        if not (fg < MIN_FOLD_GB):
            return waited
        time.sleep(60)
        waited += 60


def run_fold(job):
    waited = wait_ram()
    t0 = time.time()
    S91.set_counts(S91.FULL_COUNTS)
    T, Q, ti, fi = job["T"], job["Q"], job["ti"], job["fi"]
    pages = job["pages"] if job.get("pages") is not None else S67.load_pages(ROOT / "data" / "translit" / f"{TRANSLITS[T]}.meta.json")
    off = 1000 * ti + 10 * fi
    seed = SEED + off
    train = [(p, q, ls) for p, q, ls in pages if q != Q]
    test = [(p, q, ls) for p, q, ls in pages if q == Q]
    tr_tok = [w for _, _, ls in train for l in ls for w in l]
    seg = SlotSegmenter(tr_tok) if job["seg"] == "slot" else S80.identity_seg_factory(tr_tok)
    cache = {}

    def core(w):
        c = cache.get(w)
        if c is None:
            c = cache[w] = seg.segment(w)[1]
        return c
    ctrain = [(p, q, [[core(w) for w in l] for l in ls]) for p, q, ls in train]
    ctest = [(p, q, [[core(w) for w in l] for l in ls]) for p, q, ls in test]
    glob = Counter()
    for _, q, ls in ctrain:
        for l in ls:
            glob.update(l)
    B = S91.bigram_of([(p, ls) for p, q, ls in ctrain])
    for a_ in list(B):   # REVISION 2: no self-transitions in the fitted transition table
        B[a_].pop(a_, None)
    prod = LP94(glob, B)
    spec_tr = [(p, q, [len(l) for l in ls]) for p, q, ls in train]
    spec_te = [(p, q, [len(l) for l in ls]) for p, q, ls in test]
    real_tr = S91.own([(p, ls) for p, q, ls in ctrain])
    target = S91.comps(S87.profile("target", real_tr, "id", N_MATCH, seed))
    F = fit_lp(prod, spec_tr, target, seed)
    H, nrep = S91.replicate_to_ntot(lambda s, j: prod.text([(p, f"r{j}:{q}", L) for p, q, L in spec_te], s, tag=f"r{j}"), 1001)
    pH = S87.profile(f"LP94_H_{T}_{Q}", H, "id", N_MATCH, seed + 1)
    te_tok = [c for _, _, ls in ctest for l in ls for c in l]
    oov = sum(1 for c in te_tok if c not in glob or c == "") / max(1, len(te_tok))
    realQ = S91.rep_small([(p, ls) for p, q, ls in ctest])
    gen1 = S91.rep_small(prod.text(spec_te, 1001, tag="r0"))
    res = dict(T=T, Q=Q, n_test=len(test), test_tok=len(te_tok), train_tok=len(tr_tok), fit=F, target=target, pH=pH,
               nrep=nrep, oov=oov, realQ=realQ, gen1=gen1, V=len(prod.items))
    res["secs"] = time.time() - t0
    res["ram_wait_s"] = waited
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    return res


def run_pool(jobs, tag, sink=None):
    import multiprocessing as mp
    out = {}
    t0 = time.time()
    ctx = mp.get_context("spawn")
    with ctx.Pool(min(N_WORKERS, len(jobs)), initializer=S91.worker_init) as pool:
        for r in pool.imap_unordered(run_fold, jobs):
            out[(r["T"], r["Q"])] = r
            print(f"  [{tag} {time.time() - t0:.0f}s] fold {r['T']} {r['Q']} done ({r['secs']:.0f}s; {r['fit']['n_evals']} evals; "
                  f"params {r['fit']['params']} loss {r['fit']['loss']:.3f})", flush=True)
            if sink is not None:
                sink(r)
    return out


def reached(r, lb):
    g, t = r["fit"]["gen"]["loc"], r["target"]["loc"]
    return S87.in_band(g, lb) and abs(g - t) <= REACH_TOL


