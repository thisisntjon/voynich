def fx_texts():
    rng = np.random.default_rng(87)
    V = 3000
    z = 1.0 / np.arange(1, V + 1)
    z /= z.sum()
    vocab = [f"w{i}" for i in range(V)]
    n_pages, n_lines = 160, 20
    line_lens = [1 + int(x) for x in rng.poisson(7, size=4000)]
    topics = [rng.choice(V, size=250, replace=False) for _ in range(NB)]

    def page_dist(pi, r):
        base = z.copy()
        t = topics[min(NB - 1, pi * NB // n_pages)]
        boost = np.zeros(V); boost[t] = r.dirichlet(np.ones(len(t)) * 0.5) * 0.6
        d = 0.4 * base + boost
        return d / d.sum()

    def pages_of(gen_line, seed):
        r = np.random.default_rng(seed)
        pages, k = [], 0
        for pi in range(n_pages):
            pdist = page_dist(pi, r)
            lines = []
            for _ in range(n_lines):
                n = line_lens[k % len(line_lens)]; k += 1
                lines.append(gen_line(r, pdist, n))
            pages.append((f"p{pi:03d}", lines))
        return pages

    def linepool(alpha):
        def g(r, pdist, n):
            kk = max(1, int(round(alpha * n)))
            pool = r.choice(V, size=kk, replace=False, p=pdist)
            w = pdist[pool] / pdist[pool].sum()
            return [vocab[i] for i in r.choice(pool, size=n, p=w)]
        return g

    def pagepool(r, pdist, n):
        return [vocab[i] for i in r.choice(V, size=n, p=pdist)]
    succ = rng.permutation(V)

    def prose_pages(seed):
        r = np.random.default_rng(seed)
        toks, cur = [], 0
        for _ in range(n_pages * n_lines * 8):
            cur = int(succ[cur]) if r.random() < 0.5 else int(r.choice(V, p=z))
            toks.append(vocab[cur])
        return toks
    out = OrderedDict()
    out["FX_linepool_A"] = ("pages", pages_of(linepool(0.6), 1))
    out["FX_linepool_B"] = ("pages", pages_of(linepool(0.6), 2))
    out["FX_pagepool"] = ("pages", pages_of(pagepool, 3))
    out["FX_prose"] = ("tokens", prose_pages(4))
    return out, line_lens, [n_lines]


