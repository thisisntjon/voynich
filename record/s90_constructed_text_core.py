def lay(T, name, line_lens, page_nl):
    t = T[name]
    if t.get("members"):
        pages = []
        for n, q in t["members"]:
            P = S87.layout([ln for ln in T[n]["lines"] if ln], True, None, line_lens, page_nl, n_tot=q)
            pages.extend((f"{n}:{pid}", ls) for pid, ls in P)
        ntok = sum(len(ln) for _, ls in pages for ln in ls)
        return cut(pages, min(ntok, N_TOT)), ntok, sum(len(ls) for _, ls in pages)
    lines = [ln for ln in t["lines"] if ln]
    ntok = sum(len(x) for x in lines)
    return S87.layout(lines, True, None, line_lens, page_nl, n_tot=min(ntok, N_TOT)), ntok, len(lines)


