def profile(name, pages, seg_kind, n_match, seed, interval=False):
    """seg_kind: 'id' (word = core) or 'slot' (SlotSegmenter).  Returns dict of the profile."""
    t = time.time()
    toks = [w for _, ls in pages for ln in ls for w in ln]
    if seg_kind == "slot":
        seg = SlotSegmenter(toks)
        cache = {}

        def core_of(w):
            c = cache.get(w)
            if c is None:
                c = cache[w] = seg.segment(w)[1]
            return c
        sf = SlotSegmenter
    else:
        def core_of(w):
            return w
        sf = S80.identity_seg_factory
    cores, pg, lid, blk, ids = flatten(pages, core_of)
    rep = repetition(cores, pg, lid, N_SHUF_R, seed)
    loc = locality(cores, blk, N_PERM_LOC, N_BOOT, seed + 2)
    T = S80.prepare(name, "S87", pages, sf)
    mset = S80.matched_set(T, n_match)
    oc, olid, opg = S80.arrays(mset)
    labs = [S80.apply_map(oc, S80.fit_freq(T["tr_counts"], K)) for K in KS]
    ordr = order_excess(labs, olid, N_SHUF_ORDER, seed + 3)
    res = dict(name=name, tokens=len(toks), pages=len(pages), lines=int(lid.max()) + 1, types=len(ids),
               empty=int((cores < 0).sum()), te_tok=T["te_tok"], n_te_pages=T["n_te"], matched_tokens=len(oc),
               order={K: dict(mm=o[0], p=o[1], plug=o[2]) for K, o in zip(KS, ordr)}, rep=rep, loc=loc,
               blocks=int(blk.max()) + 1)
    if interval:
        ci = order_interval(labs, olid, opg, FX_INT_DRAWS, 20, seed + 4)
        for K, c in zip(KS, ci):
            res["order"][K]["ci"] = c
    res["secs"] = time.time() - t
    return res


